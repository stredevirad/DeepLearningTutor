"""
Equivalent Python Code Export
=============================
Generates a standalone training script that reproduces exactly what the user
trained in the app: same dataset handling, same leakage-free preprocessing
(split first, fit the scaler on the training split only), same architecture,
optimizer, learning rate, batch size, epochs, early stopping and random seed.
"""

from textwrap import dedent

SKLEARN_LOADERS = {"Iris": "load_iris", "Wine": "load_wine",
                   "Breast Cancer": "load_breast_cancer", "Digits": "load_digits"}
KERAS_LOADERS = {"MNIST": "mnist", "Fashion-MNIST": "fashion_mnist"}
FASHION_CLASSES = ["T-shirt", "Trouser", "Pullover", "Dress", "Coat",
                   "Sandal", "Shirt", "Sneaker", "Bag", "Ankle boot"]


def _num(value):
    """Format a number the way a person would type it (0.001, not 0.0010000000474974513)."""
    return repr(float(value)) if isinstance(value, float) else repr(value)


def _describe(cfg):
    if cfg["network_type"] == "Simple NN":
        arch = f"{cfg['hidden_layers']} hidden layer(s) x {cfg['nodes_per_layer']} nodes"
    else:
        arch = f"{cfg['conv_layers']} conv layer(s), {cfg['base_filters']} base filters"
    es = "on" if cfg.get("early_stopping") else "off"
    return (f"{cfg['network_type']} on {cfg['dataset']} | {arch} | dropout {cfg['dropout_rate']} | "
            f"{cfg['optimizer']} lr={cfg['learning_rate']} | batch {cfg['batch_size']} | "
            f"{cfg['epochs']} epochs | early stopping {es} | seed {cfg.get('seed', 42)}")


def _header(cfg, extra_imports):
    imports = ["import numpy as np", "import tensorflow as tf"] + extra_imports
    return (
        '"""\n'
        "Equivalent training script generated by Deep Learning Tutor.\n"
        f"Configuration: {_describe(cfg)}\n"
        '"""\n'
        + "\n".join(imports) + "\n\n"
        f"SEED = {int(cfg.get('seed', 42))}\n"
        "tf.keras.utils.set_random_seed(SEED)  # seeds Python, NumPy and TensorFlow for reproducible runs\n"
    )


def _split_block(stratified=True):
    strat = ", stratify=y" if stratified else ""
    note = ("# stratify=y keeps the class proportions the same in both splits\n" if stratified
            else "# (not stratified: some classes have too few examples)\n")
    return (
        "\n# --- Split FIRST (80% train / 20% validation) ---\n"
        + note
        + f"X_train, X_val, y_train, y_val = train_test_split(\n"
        f"    X, y, test_size=0.2, random_state=SEED{strat})\n"
    )


def _dense_model(cfg):
    lines = ["model = tf.keras.Sequential([", "    tf.keras.Input(shape=(X_train.shape[1],)),"]
    for _ in range(int(cfg["hidden_layers"])):
        lines.append(f"    tf.keras.layers.Dense({int(cfg['nodes_per_layer'])}, activation=\"relu\"),")
        if float(cfg["dropout_rate"]) > 0:
            lines.append(f"    tf.keras.layers.Dropout({_num(float(cfg['dropout_rate']))}),")
    lines.append("    tf.keras.layers.Dense(num_classes, activation=\"softmax\"),")
    lines.append("])")
    return "\n# --- Build Model ---\n" + "\n".join(lines) + "\n"


def _cnn_model(cfg):
    lines = ["model = tf.keras.Sequential([", "    tf.keras.Input(shape=(28, 28, 1)),"]
    filters = int(cfg["base_filters"])
    for _ in range(int(cfg["conv_layers"])):
        lines.append(f"    tf.keras.layers.Conv2D({filters}, (3, 3), activation=\"relu\", padding=\"same\"),")
        lines.append("    tf.keras.layers.MaxPooling2D((2, 2)),")
        filters *= 2
    lines.append("    tf.keras.layers.Flatten(),")
    lines.append("    tf.keras.layers.Dense(64, activation=\"relu\"),")
    if float(cfg["dropout_rate"]) > 0:
        lines.append(f"    tf.keras.layers.Dropout({_num(float(cfg['dropout_rate']))}),")
    lines.append("    tf.keras.layers.Dense(num_classes, activation=\"softmax\"),")
    lines.append("])")
    return "\n# --- Build Model ---\n" + "\n".join(lines) + "\n"


def _train_block(cfg):
    callbacks = "[]"
    es = ""
    if cfg.get("early_stopping"):
        es = ("# Stop when validation loss has not improved for 5 epochs and keep the best weights\n"
              "early_stopping = tf.keras.callbacks.EarlyStopping(\n"
              "    monitor=\"val_loss\", patience=5, restore_best_weights=True)\n")
        callbacks = "[early_stopping]"
    return (
        "\n# --- Compile ---\n"
        f"optimizer = tf.keras.optimizers.{cfg['optimizer']}(learning_rate={_num(float(cfg['learning_rate']))})\n"
        "model.compile(optimizer=optimizer, loss=\"sparse_categorical_crossentropy\", metrics=[\"accuracy\"])\n"
        "model.summary()\n"
        "\n# --- Train ---\n"
        + es +
        f"history = model.fit(X_train, y_train, epochs={int(cfg['epochs'])}, batch_size={int(cfg['batch_size'])},\n"
        f"                    validation_data=(X_val, y_val), callbacks={callbacks})\n"
        "\n# --- Evaluate (on the weights the model ended with) ---\n"
        "loss, acc = model.evaluate(X_val, y_val, verbose=0)\n"
        "print(f\"Validation accuracy: {acc:.4f} | validation loss: {loss:.4f}\")\n"
        "\n# --- Save Model ---\n"
        "model.save(\"my_model.keras\")\n"
        "print(\"Model saved to my_model.keras\")\n"
    )


def _builtin_tabular(cfg):
    loader = SKLEARN_LOADERS[cfg["dataset"]]
    body = (
        f"\n# --- Load Dataset ({cfg['dataset']}) ---\n"
        f"data = {loader}()\n"
        "X, y = data.data, data.target\n"
        "class_names = list(data.target_names)\n"
        "num_classes = len(class_names)\n"
        + _split_block(True) +
        "\n# --- Scale features: fit on the TRAINING split only, then reuse for validation ---\n"
        "# (fitting on all of X would leak information about the validation data)\n"
        "scaler = StandardScaler()\n"
        "X_train = scaler.fit_transform(X_train)\n"
        "X_val = scaler.transform(X_val)\n"
    )
    header = _header(cfg, [f"from sklearn.datasets import {loader}",
                           "from sklearn.model_selection import train_test_split",
                           "from sklearn.preprocessing import StandardScaler"])
    return header + body + _dense_model(cfg) + _train_block(cfg)


def _custom_csv(cfg, meta):
    target = meta.get("target_column") or cfg.get("target_column") or "target"
    numeric = list(meta.get("numeric_columns", []))
    categorical = list(meta.get("categorical_columns", []))
    transformers = []
    if numeric:
        transformers.append("    (\"num\", StandardScaler(), NUMERIC),")
    if categorical:
        transformers.append("    (\"cat\", OneHotEncoder(handle_unknown=\"ignore\", sparse_output=False), CATEGORICAL),")
    body = (
        "\n# --- Load Custom Dataset ---\n"
        f"df = pd.read_csv({meta.get('file_name', 'your_dataset.csv')!r})  # ⚠️ change to the path of your CSV file\n"
        f"TARGET = {target!r}\n"
        f"NUMERIC = {numeric!r}\n"
        f"CATEGORICAL = {categorical!r}  # text columns with few distinct values -> one-hot encoded\n"
        "\n# --- Clean ---\n"
        "df = df.dropna(subset=[TARGET])                      # rows without a label cannot be used\n"
        "for col in NUMERIC:\n"
        "    df[col] = pd.to_numeric(df[col], errors=\"coerce\")  # stray text -> NaN\n"
        "df = df.dropna(subset=NUMERIC)                       # drop rows with missing numbers\n"
        "for col in CATEGORICAL:\n"
        "    df[col] = df[col].where(df[col].notna(), \"(missing)\").astype(str)\n"
        "\n"
        "labels = df[TARGET] if pd.api.types.is_numeric_dtype(df[TARGET]) else df[TARGET].astype(str)\n"
        "class_values = sorted(labels.unique(), key=lambda v: (isinstance(v, str), v))\n"
        "class_names = [str(int(v)) if isinstance(v, float) and v.is_integer() else str(v) for v in class_values]\n"
        "num_classes = len(class_names)\n"
        "y = labels.map({v: i for i, v in enumerate(class_values)}).to_numpy()\n"
        "X = df[NUMERIC + CATEGORICAL]\n"
        "print(f\"{len(X)} samples, {num_classes} classes: {class_names}\")\n"
        + _split_block(meta.get("stratified", True)) +
        "\n# --- Preprocess: fit on the TRAINING split only, then reuse for validation (no leakage) ---\n"
        "preprocess = ColumnTransformer([\n"
        + "\n".join(transformers) + "\n"
        "])\n"
        "X_train = preprocess.fit_transform(X_train)\n"
        "X_val = preprocess.transform(X_val)\n"
    )
    header = _header(cfg, ["import pandas as pd",
                           "from sklearn.compose import ColumnTransformer",
                           "from sklearn.model_selection import train_test_split",
                           "from sklearn.preprocessing import OneHotEncoder, StandardScaler"])
    return header + body + _dense_model(cfg) + _train_block(cfg)


def _builtin_images(cfg):
    loader = KERAS_LOADERS[cfg["dataset"]]
    names = FASHION_CLASSES if cfg["dataset"] == "Fashion-MNIST" else [str(i) for i in range(10)]
    body = (
        f"\n# --- Load Dataset ({cfg['dataset']}) ---\n"
        "# Keras provides a fixed train/test split; the test split is used for validation.\n"
        f"(X_train, y_train), (X_val, y_val) = tf.keras.datasets.{loader}.load_data()\n"
        "X_train = X_train.astype(np.float32)[..., np.newaxis] / 255.0  # scale pixels to [0, 1], add channel axis\n"
        "X_val = X_val.astype(np.float32)[..., np.newaxis] / 255.0\n"
        f"class_names = {names!r}\n"
        "num_classes = len(class_names)\n"
    )
    return _header(cfg, []) + body + _cnn_model(cfg) + _train_block(cfg)


_IMAGE_LOADER = dedent('''
    # --- Load Custom Image Dataset ---
    # One sub-folder per class, e.g. your_dataset/cats/1.png, your_dataset/dogs/7.jpg
    DATA_DIR = Path({folder!r})  # ⚠️ change to the folder you zipped
    CLASS_NAMES = {classes!r}
    EXTENSIONS = {{".png", ".jpg", ".jpeg", ".bmp", ".gif", ".webp"}}


    def load_image(path):
        """Same preprocessing as the app: grayscale, dark background, object scaled to fill 28x28."""
        arr = np.asarray(Image.open(path).convert("L"), dtype=np.float32)
        k = max(1, min(arr.shape) // 8)
        corners = np.concatenate([arr[:k, :k].ravel(), arr[:k, -k:].ravel(),
                                  arr[-k:, :k].ravel(), arr[-k:, -k:].ravel()])
        if corners.mean() > 127:          # light background -> invert (object bright, background dark)
            arr = 255.0 - arr
        mask = arr > arr.max() * 0.15
        b = max(1, round(0.01 * min(arr.shape))) if min(arr.shape) > 8 else 0
        if b:                             # ignore thin frames around the picture
            mask[:b, :] = mask[-b:, :] = mask[:, :b] = mask[:, -b:] = False
        if mask.any():                    # crop to the object
            rows, cols = np.where(mask.any(axis=1))[0], np.where(mask.any(axis=0))[0]
            arr = arr[rows[0]:rows[-1] + 1, cols[0]:cols[-1] + 1]
        side = max(arr.shape)             # pad to a square, then resize to 28x28
        square = np.zeros((side, side), dtype=np.float32)
        top, left = (side - arr.shape[0]) // 2, (side - arr.shape[1]) // 2
        square[top:top + arr.shape[0], left:left + arr.shape[1]] = arr
        small = Image.fromarray(np.clip(square, 0, 255).astype(np.uint8)).resize((28, 28), Image.LANCZOS)
        return np.asarray(small, dtype=np.float32) / 255.0


    images, labels = [], []
    for label, class_name in enumerate(CLASS_NAMES):
        for path in sorted((DATA_DIR / class_name).rglob("*")):
            if path.suffix.lower() in EXTENSIONS:
                images.append(load_image(path))
                labels.append(label)
    X = np.stack(images)[..., np.newaxis]
    y = np.array(labels)
    class_names = CLASS_NAMES
    num_classes = len(class_names)
    print(f"{{len(X)}} images, {{num_classes}} classes: {{class_names}}")
''')


def _custom_images(cfg, meta):
    classes = list(meta.get("class_names", []))
    body = _IMAGE_LOADER.format(folder=meta.get("folder", "your_dataset"), classes=classes)
    body += _split_block(meta.get("stratified", True))
    header = _header(cfg, ["from pathlib import Path", "from PIL import Image",
                           "from sklearn.model_selection import train_test_split"])
    return header + body + _cnn_model(cfg) + _train_block(cfg)


def generate_training_code(cfg, meta=None):
    """Return a runnable Python script for the trained configuration `cfg`.

    `meta` describes custom datasets:
      CSV: {"target_column", "numeric_columns", "categorical_columns", "stratified", "file_name"}
      ZIP: {"class_names", "stratified", "folder"}
    """
    meta = meta or {}
    cfg = dict(cfg)
    cfg.setdefault("seed", 42)
    if cfg["network_type"] == "Simple NN":
        if cfg.get("using_custom"):
            return _custom_csv(cfg, meta)
        return _builtin_tabular(cfg)
    if cfg.get("using_custom"):
        return _custom_images(cfg, meta)
    return _builtin_images(cfg)
